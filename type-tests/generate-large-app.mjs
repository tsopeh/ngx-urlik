// Writes a 201-route app as one literal, the way an app writes its router file. `npm run typecheck`
// checks it as a type test, so a type change that slows big route trees, or hits TypeScript's
// depth limit, fails.
import { writeFileSync } from 'node:fs';

const sections = 50;
const names = ['ROOT'];
const routes = [];
const reads = [];
for (let i = 0; i < sections; i++) {
  names.push(`LIST_${i}`, `DETAIL_${i}`, `SUB_${i}`, `LEAF_${i}`);
  routes.push(`{
        path: 's${i}',
        queryParams: {
          a${i}: queryParam({ codec: stringCodec(), defaultValue: '' }),
          b${i}: queryParam({ codec: numberCodec(), defaultValue: 1 }),
        },
        children: [
          { path: '', pathMatch: 'full', routeName: RouteNames.LIST_${i}, component: Page },
          {
            path: ':id${i}',
            routeName: RouteNames.DETAIL_${i},
            pathParam: { id${i}: numberCodec() },
            canActivate: [(route) => route.paramMap.has('id${i}')],
            component: Page,
            children: [
              {
                path: 'sub/:sub${i}',
                routeName: RouteNames.SUB_${i},
                component: Page,
                children: [{ path: 'leaf/:leaf${i}', routeName: RouteNames.LEAF_${i}, component: Page }],
              },
            ],
          },
        ],
      }`);
  reads.push(
    `appRouter.routes.LEAF_${i}.params().path.id${i} satisfies number;`,
    `appRouter.routes.LEAF_${i}.createUrlTree({ path: { id${i}: 1, sub${i}: 'a', leaf${i}: 'b' }, query: { b${i}: 2 } });`,
  );
}

const file = `// Generated by generate-large-app.mjs. Don't edit.
import { Component, type InjectionToken } from '@angular/core';
import { defineAppRouter, numberCodec, queryParam, stringCodec } from 'ngx-urlik';
import { describe, it } from 'vitest';

@Component({ template: '' })
class Page {}

enum RouteNames {
${names.map((name) => `  ${name} = '${name}',`).join('\n')}
}

const { AppRouter } = defineAppRouter(RouteNames, {
  routes: [
    {
      path: '',
      routeName: RouteNames.ROOT,
      component: Page,
      queryParams: { search: queryParam({ codec: stringCodec(), defaultValue: '' }) },
      children: [
      ${routes.join(',\n      ')},
      ],
    },
  ],
});

declare const appRouter: typeof AppRouter extends InjectionToken<infer Value> ? Value : never;

describe('a 201-route app', () => {
  it('type-checks, with every route typed', () => {
${reads.map((line) => `    ${line}`).join('\n')}
  });
});
`;

writeFileSync(new URL('./large-app.generated.test-d.ts', import.meta.url), file);
